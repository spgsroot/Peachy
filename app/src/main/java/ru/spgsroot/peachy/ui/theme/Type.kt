/**
 * Onest static instances (OFL): Regular, Medium and SemiBold. The three files keep the
 * app's weights exact on every supported API level; no weight is requested at runtime.
 * Onest is metrically close to Roboto (x-height 527 vs 528 per 1000 em), so the Material
 * sizes and line heights below stay valid while Cyrillic and Latin share one face.
 */
